void draw_char(std::vector<unsigned char>& out_img, int out_w, int out_h, int start_x, int start_y, char c, unsigned char brightness) {
    int font_idx = c - 32; 
    if (font_idx < 0 || font_idx >= 95) font_idx = 0; 
    for (int ky = 0; ky < 8; ++ky) {
        for (int kx = 0; kx < 8; ++kx) {
            int pixel_x = start_x + kx;
            int pixel_y = start_y + ky;
            if (pixel_x < out_w && pixel_y < out_h) {
                bool is_font_pixel = (font8x8[font_idx][ky] >> (7 - kx)) & 1;
                int out_idx = pixel_y * out_w + pixel_x;
                out_img[out_idx] = is_font_pixel ? brightness : 0;
            }
        }
    }
}

int main(int argc, char* argv[]) {
    std::string filename;
    if (argc > 1) {
        filename = argv[1];
    } else {
        filename = "image.png"; 
    }
    int width, height, channels;
    unsigned char* img = stbi_load(filename.c_str(), &width, &height, &channels, 1);
    if (img == nullptr) {
        std::cerr << "failed to upload image" << filename << std::endl;
        std::cout << "press enter to exit...";
        std::cin.get();
        return 1;
    }
    std::string ascii_chars = "$@B%8&WM#*oahkbdpqwmZO0QLCJUYXzcvunxrjft/\\|()1{}[]?-_+~<>i!lI;:,\"^`'. ";
    int num_chars = ascii_chars.length();

    int font_size = 8;
    int cols = width / font_size;
    int rows = height / font_size;
    if (cols < 1) cols = 1;
    if (rows < 1) rows = 1;
    std::vector<unsigned char> out_img(width * height, 0); 
    int step_x = width / cols;
    int step_y = height / rows;

    for (int r = 0; r < rows; ++r) {
        for (int c = 0; c < cols; ++c) {
            int orig_x = c * step_x + step_x / 2;
            int orig_y = r * step_y + step_y / 2;
            if (orig_x >= width) orig_x = width - 1;
            if (orig_y >= height) orig_y = height - 1;
            unsigned char brightness = img[orig_y * width + orig_x];
            int char_index = brightness * (num_chars - 1) / 255;
            char target_char = ascii_chars[char_index];
            int start_x = c * font_size;
            int start_y = r * font_size;
            draw_char(out_img, width, height, start_x, start_y, target_char, brightness);
        }
    }
    std::string output_filename = "output_ascii.png";
    int success = stbi_write_png(output_filename.c_str(), width, height, 1, out_img.data(), width);
    if (success) {
        std::cout << "ascii file save as: " << output_filename << std::endl;
    } else {
        std::cerr << "error saving png file" << std::endl;
    }
    stbi_image_free(img);
    std::cout << "done! press enter to exit...";
    std::cin.get();
    return 0;
}
